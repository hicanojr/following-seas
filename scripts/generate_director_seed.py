"""Generate supabase/seed/director-lab-services.sql from the trial tracker workbook.

Usage (read only; the workbook is never modified):

    python3 -I scripts/generate_director_seed.py \
        /mnt/project-files/job-search/director-lab-services-tracker.xlsx \
        > supabase/seed/director-lab-services.sql

Reads the "Search log" and "Profile and scoring" sheets. Requires openpyxl.
"""

import json
import re
import sys

import openpyxl

SOURCES = {"indeed": "indeed", "ziprecruiter": "ziprecruiter", "linkedin": "linkedin", "usajobs": "usajobs"}
QUALITY = {"good": "good", "mixed": "mixed", "noise": "noise"}


def sql_str(value):
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def sql_json(value):
    return sql_str(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def sql_text_array(items):
    return "array[" + ", ".join(sql_str(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


def parse_filters(source, text):
    """Best-effort structured filters. query_text always keeps the original wording."""
    filters = {}
    m = re.search(r"min \$([\d,]+)", text)
    if m:
        filters["min_salary"] = int(m.group(1).replace(",", ""))
    m = re.search(r"\((\d+) pages?\)", text)
    if m:
        filters["pages"] = int(m.group(1))
    lowered = text.lower()
    if "remote or hybrid" in lowered:
        filters["remote"] = True
        filters["hybrid"] = True
    elif re.search(r"\bremote\b", lowered):
        filters["remote"] = True
    if source == "indeed" and "," in text:
        loc = text.rsplit(",", 1)[1].strip()
        if loc and not loc.lower().startswith(("remote", "min ")):
            filters["location"] = loc
    return filters


def parse_hits(notes):
    if not notes:
        return None, None
    m = re.match(r"\s*(\d+) of (\d+) relevant", notes)
    if m:
        return int(m.group(1)), int(m.group(2))
    if notes.strip().lower().startswith("zero results"):
        return 0, 0
    return None, None


def read_profile(ws):
    data = {}
    for row in ws.iter_rows(min_row=2, values_only=True):
        if row and row[0]:
            data[str(row[0]).strip()] = str(row[1]).strip() if row[1] is not None else ""
    return data


def main(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    prof = read_profile(wb["Profile and scoring"])

    titles = []
    for t in prof["Target titles"].split(";"):
        t = re.sub(r"\s*\(.*?\)\s*$", "", t).strip()
        if t:
            titles.append(t)
    pay = re.search(r"\$([\d,]+)", prof["Minimum pay"])
    min_pay = int(pay.group(1).replace(",", "")) if pay else None
    locations = [] if prof["Location"].strip().lower() in ("any location", "any", "anywhere") else [prof["Location"]]

    must_haves = [
        {"key": "min_base_pay", "label": "Base pay at or above minimum", "detail": prof["Minimum pay"]},
        {"key": "administrative_role", "label": "Administrative laboratory leadership role",
         "detail": "Target titles are administrative roles, not CLIA laboratory director roles."},
    ]
    deal_breakers = [] if prof["Deal-breakers"].strip().lower().startswith("none") else [
        {"label": d.strip()} for d in prof["Deal-breakers"].split(";") if d.strip()
    ]
    plus_factors = [{"label": p.strip().capitalize()} for p in re.split(r",|;", prof["Plus factors"]) if p.strip()]
    rubric = {
        "bands": [
            {"range": [9, 10], "rule": prof["Score 9 to 10"]},
            {"range": [7, 8], "rule": prof["Score 7 to 8"]},
            {"range": [5, 6], "rule": prof["Score 5 to 6"]},
            {"range": [1, 4], "rule": prof["Score 1 to 4"]},
        ],
        "always_flag_as_gap": [prof["Always flagged as a gap"]],
        "facts_source": "Career facts sheet only. Never invent resume facts.",
        "easy_apply_default": "unknown",
    }

    queries = []
    for row in wb["Search log"].iter_rows(min_row=2, values_only=True):
        if not row or not row[0] or not row[1]:
            continue
        source = SOURCES[str(row[0]).strip().lower().replace(" ", "")]
        text = str(row[1]).strip()
        quality = QUALITY[str(row[2]).strip().lower()] if row[2] else "untested"
        notes = str(row[3]).strip() if row[3] else None
        relevant, total = parse_hits(notes)
        queries.append((source, text, parse_filters(source, text), quality, relevant, total, quality == "noise", notes))

    out = []
    w = out.append
    w("-- Seed: Director of Laboratory Services profile and its query library from the trial.")
    w("-- Generated by scripts/generate_director_seed.py from director-lab-services-tracker.xlsx.")
    w("-- Do not hand-edit; regenerate instead.")
    w("--")
    w("-- Needs the target user's id (auth.users.id). Run with psql:")
    w("--   psql \"$DATABASE_URL\" -v ON_ERROR_STOP=1 \\")
    w("--     -c \"select set_config('seed.user_id', '<USER_UUID>', false)\" \\")
    w("--     -f supabase/seed/director-lab-services.sql")
    w("-- Or in the Supabase SQL editor, put this line above the file contents and run both:")
    w("--   select set_config('seed.user_id', '<USER_UUID>', false);")
    w("--")
    w("-- Idempotent: running it twice does not duplicate the profile or queries.")
    w("")
    w("do $seed$")
    w("declare")
    w("  v_user uuid := nullif(current_setting('seed.user_id', true), '')::uuid;")
    w("  v_profile uuid;")
    w("begin")
    w("  if v_user is null then")
    w("    raise exception 'Set seed.user_id first: select set_config(''seed.user_id'', ''<uuid>'', false);';")
    w("  end if;")
    w("  if not exists (select 1 from auth.users where id = v_user) then")
    w("    raise exception 'No auth.users row with id %. Sign in once with that account first.', v_user;")
    w("  end if;")
    w("")
    w("  select id into v_profile from public.profiles")
    w(f"   where user_id = v_user and lower(name) = lower({sql_str(prof['Profile name'])}) and deleted_at is null;")
    w("")
    w("  if v_profile is null then")
    w("    insert into public.profiles")
    w("      (user_id, name, target_titles, locations, min_base_pay, must_haves, deal_breakers, plus_factors, scoring_rubric, notes)")
    w("    values (")
    w("      v_user,")
    w(f"      {sql_str(prof['Profile name'])},")
    w(f"      {sql_text_array(titles)},")
    w(f"      {sql_text_array(locations)},")
    w(f"      {min_pay if min_pay is not None else 'null'},")
    w(f"      {sql_json(must_haves)},")
    w(f"      {sql_json(deal_breakers)},")
    w(f"      {sql_json(plus_factors)},")
    w(f"      {sql_json(rubric)},")
    w(f"      {sql_str('Seeded from the trial tracker built ' + prof.get('Built', '').split(' from ')[0] + '.')}")
    w("    )")
    w("    returning id into v_profile;")
    w("  end if;")
    w("")
    w("  insert into public.queries")
    w("    (user_id, profile_id, source, query_text, filters, quality, runs, relevant_hits, total_hits, retired, notes)")
    w("  values")
    rows = []
    for source, text, filters, quality, relevant, total, retired, notes in queries:
        rows.append(
            "    (v_user, v_profile, "
            f"{sql_str(source)}, {sql_str(text)}, {sql_json(filters)}, {sql_str(quality)}, 1, "
            f"{'null' if relevant is None else relevant}, {'null' if total is None else total}, "
            f"{'true' if retired else 'false'}, {sql_str(notes)})"
        )
    w(",\n".join(rows))
    w("  on conflict (profile_id, source, query_text) do nothing;")
    w("end;")
    w("$seed$;")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: generate_director_seed.py <path-to-xlsx>")
    main(sys.argv[1])
